
CREATE TABLE IF NOT EXISTS plate_scans (
    scan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate VARCHAR(50) NOT NULL,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    image_path VARCHAR(500),
    crop_image_path VARCHAR(500),
    plate_color_code VARCHAR(20),
    plate_color_label VARCHAR(100),
    plate_color_confidence DOUBLE PRECISION,
    color_code VARCHAR(20),
    scan_time TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    note VARCHAR(200),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_plate_scans_plate
    ON plate_scans (plate);

CREATE INDEX IF NOT EXISTS ix_plate_scans_scan_time
    ON plate_scans (scan_time);
